--Q9 Which brand generate the most revenue potential?
CREATE VIEW MOST_REVENUE_POTENTIAL_BRAND AS
SELECT TOP(5)
CAR_BRAND,
COUNT(*) AS PURCHASES,
SUM(CONVERT(BIGINT, OFFER_PRICE)) AS TOTAL_VALUE
FROM CARS24_DATA
WHERE BOOKING_STATUS = 'Purchased'
GROUP BY CAR_BRAND
ORDER BY TOTAL_VALUE DESC;




--Q10 Which brand contributes the highest total business value while maintaining strong sales volume?
CREATE VIEW HIGHEST_TOTAL_BV_AND_STRONG_SALES AS
SELECT TOP(5)
CAR_BRAND,
COUNT(*) AS TOTAL_PURCHASES,
SUM(CONVERT(BIGINT, OFFER_PRICE)) AS TOTAL_BUSINESS_VALUE
FROM CARS24_DATA
WHERE BOOKING_STATUS = 'Purchased'
GROUP BY CAR_BRAND
ORDER BY TOTAL_BUSINESS_VALUE DESC,TOTAL_PURCHASES DESC;



